def _default_cell(setting: SettingDoc) -> str:
    if setting.secret and setting.default == "(secret)":
        return "_(set)_"
    if setting.default in ("''", '""'):
        return "_(blank)_"
    return f"`{setting.default}`"


def render_environment() -> str:
    settings_list = catalog()
    sections: dict[str, list[SettingDoc]] = defaultdict(list)
    for setting in settings_list:
        sections[setting.section].append(setting)

    required = [s for s in settings_list if s.required]

    out: list[str] = [
        "# Environment variables",
        "",
        _GENERATED,
        "",
        f"{len(settings_list)} settings, read from the process environment or "
        "from `.env` (both `backend/.env` and the repository-root `.env` are "
        "searched, in that order). Names are case-insensitive; unknown "
        "variables are ignored rather than refused.",
        "",
        "**Types.** `bool` accepts `true`/`false`/`1`/`0`. A `str` that reads "
        "as a list is comma-separated — with one exception: "
        "`COMPLIANCE_PHYSICAL_ADDRESS` contains commas and is a single value, "
        "so quote it in `.env`.",
        "",
        "**Required.** Every field carries a default, so nothing is required "
        "in pydantic's sense, and asking pydantic returns 151 optional "
        "settings. The table below marks the ones whose shipped default is "
        "blank or a placeholder. For most of those, blank means the feature "
        "behind them is off until a value is supplied; for a few it means "
        "*derive it* — each entry says which, and that is why the table quotes "
        "the prose rather than a verdict.",
        "",
        "**Checked at startup.** Some settings are validated when the process "
        "boots and will refuse to start on a bad value rather than "
        "misbehaving later. Those are marked, with the guard named.",
        "",
        "**`.env.example`.** The template ships the subset an operator usually "
        "sets. A setting absent from it is still settable — this catalogue, "
        "not that file, is the complete list.",
        "",
        "## Settings that ship blank",
        "",
        "| Variable | Section | What the blank default means |",
        "| --- | --- | --- |",
    ]
    for setting in required:
        out.append(
            f"| `{setting.env_var}` | {setting.section} | "
            f"{_one_line(setting.description, 110)} |"
        )
    out += ["", "## By section", ""]
    for section in sections:
        out.append(f"- [{section}](#{_anchor(section)})")
    out.append("")

    for section, group in sections.items():
        out += [f"## {section}", ""]
        for setting in group:
            flags = []
            if setting.required:
                flags.append("ships blank")
            if setting.secret:
                flags.append("secret")
            if setting.validated_by:
                flags.append(
                    "checked at startup by "
                    + ", ".join(f"`{name}`" for name in setting.validated_by)
                )
            if not setting.in_env_example:
                flags.append("not in `.env.example`")
            out += [
                f"### `{setting.env_var}`",
                "",
                f"`{setting.type_name}` · default {_default_cell(setting)}"
                + (f" · {', '.join(flags)}" if flags else ""),
                "",
            ]
            body = setting.description
            if setting.shared_description:
                body = (
                    "_Declared alongside the settings above it; the note covers "
                    "the group._\n\n" + body
                )
            out += [body, ""]

    return "\n".join(out).rstrip() + "\n"


