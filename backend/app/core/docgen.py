"""Render the checked-in API reference from the running application.

Four artifacts, all under ``docs/api/``, all generated and none hand-edited:

``openapi.json``
    The published schema, byte-identical to what ``/openapi.json`` serves. In
    the repository so that a client generator, a diff on a pull request, or a
    reviewer without the app running can all read it.
``API-REFERENCE.md``
    The same thing for a human: every operation grouped by resource, with its
    authentication requirement, its budget and the codes it can answer.
``ERRORS.md``
    The failures, indexed by status code rather than by route — the direction
    somebody actually arrives from, holding a 409 and wanting to know why.
``ENVIRONMENT.md``
    Every setting ``Settings`` accepts, from :mod:`app.core.settings_docs`.

Kept honest by regeneration, not by review: :mod:`tests.test_api_catalog`
rebuilds all four in memory and fails if the files on disk differ, so a new
route or a new setting cannot land with the documents describing the old shape.
"""
from __future__ import annotations

import json
import pathlib
from collections import defaultdict

from fastapi import FastAPI

from app.core.apidocs import (
    STATUS_GUIDE,
    TAG_DESCRIPTIONS,
    RouteDoc,
    enrich,
    route_docs,
)
from app.core.settings_docs import SettingDoc, catalog

_GENERATED = (
    "<!-- Generated by `python -m app.core.docgen` (backend/). Do not edit by "
    "hand: tests/test_api_catalog.py regenerates this file and fails on a "
    "difference. -->"
)


def docs_dir() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parents[3] / "docs" / "api"


def _anchor(text: str) -> str:
    """A GitHub-flavoured heading anchor.

    Punctuation is dropped rather than replaced — "AI (OpenRouter)" anchors as
    ``#ai-openrouter``, and a link built by substituting hyphens for the
    brackets points at nothing.
    """
    slug = "".join(c if c.isalnum() or c in " -" else "" for c in text.lower())
    return slug.replace(" ", "-")


def _one_line(text: str, limit: int = 160) -> str:
    """First sentence-ish of a description, flattened for a table cell."""
    flat = " ".join(text.split())
    if len(flat) <= limit:
        return flat
    return flat[: limit - 1].rsplit(" ", 1)[0] + "…"


# ---------------------------------------------------------------------------
# openapi.json
# ---------------------------------------------------------------------------


def render_openapi(app: FastAPI) -> str:
    # sort_keys so a regenerated file diffs on content rather than on dict
    # ordering, and a trailing newline so the file ends the way every other
    # text file in the repository does.
    return json.dumps(enrich(app), indent=2, sort_keys=True) + "\n"


