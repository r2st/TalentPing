def render_all(app: FastAPI) -> dict[str, str]:
    """Every generated document, keyed by filename."""
    return {
        "openapi.json": render_openapi(app),
        "API-REFERENCE.md": render_reference(app),
        "ERRORS.md": render_errors(app),
        "ENVIRONMENT.md": render_environment(),
    }


def write_all() -> list[pathlib.Path]:
    from app.main import app

    target = docs_dir()
    target.mkdir(parents=True, exist_ok=True)
    written = []
    for name, body in render_all(app).items():
        path = target / name
        path.write_text(body, encoding="utf-8")
        written.append(path)
    return written


if __name__ == "__main__":  # pragma: no cover - operator entrypoint
    for path in write_all():
        print(path)
