# What to do about each code, written for whoever is holding the response.
RESOLUTION: dict[int, str] = {
    400: (
        "Read `detail`: it names the value that cannot be acted on. Fix the "
        "request. Retrying it unchanged always fails."
    ),
    401: (
        "If `detail` is `Could not validate credentials`, the token is "
        "missing, malformed or expired — log in again. If it is "
        "`Session has been revoked; sign in again`, the account's password "
        "changed since this token was issued and every token for it is dead; "
        "the client must clear its stored token and show the login screen "
        "rather than retry."
    ),
    403: (
        "`Inactive user` means the account is disabled — nothing the client "
        "can do. `Administrator access is required` means the route is "
        "admin-only; grant the role by adding the address to `ADMIN_EMAILS` "
        "and signing in again, or through the admin API."
    ),
    404: (
        "The id does not exist, or it belongs to another account. Those are "
        "deliberately the same answer, so do not read a 404 as proof the "
        "resource is absent. Re-list the collection rather than retrying the "
        "id."
    ),
    409: (
        "The resource is in a state that refuses this call — an illegal "
        "transition, a duplicate, or a writer that got there first. Re-read "
        "the resource and decide from its current state; a blind retry either "
        "fails identically or acts on a stale assumption."
    ),
    410: (
        "The artifact was deleted by its retention sweep "
        "(`FORM_APPLY_ARTIFACT_RETENTION_DAYS`). It is not coming back. Stop "
        "offering the link."
    ),
    413: (
        "The upload is over `MAX_UPLOAD_MB`. `detail` names the file and the "
        "ceiling."
    ),
    415: (
        "The file's content type is not one the parser handles. `detail` "
        "lists what is accepted."
    ),
    422: (
        "Request validation. The body's `detail` is a list of "
        "`{loc, msg, type}` naming each offending field. Where a handler "
        "raises 422 by hand, `detail` is a sentence instead — the value "
        "parsed but cannot mean anything."
    ),
    429: (
        "Wait `Retry-After` seconds, then retry once. Do not retry "
        "immediately: the limit is a sliding window and an early retry is "
        "refused again, which is how a rate limit becomes a retry storm. On a "
        "per-address scope behind a proxy, check `TRUSTED_PROXY_HOPS` before "
        "concluding the caller was actually over budget."
    ),
    500: (
        "Nothing the client can fix. Capture `request_id` from the body — the "
        "same value is on the server's log record — and report it. The detail "
        "is always the constant string; the traceback is deliberately not sent."
    ),
    502: (
        "An upstream failed. `detail` carries the upstream's message. "
        "Retryable, with backoff."
    ),
    503: (
        "A dependency this route needs is not configured or not reachable — "
        "no model provider in the chain, no connected mailbox, "
        "`TOKEN_ENCRYPTION_KEY` unset, or workers disabled. `detail` names "
        "which. Operator action, not client action; check `/api/v1/health`."
    ),
}


def render_errors(app: FastAPI) -> str:
    routes = route_docs(app)

    # code -> detail string -> the operations that can answer with it.
    #
    # Seeded from the published document rather than from the raise sites, so
    # the catalogue covers exactly what the schema promises. The two are not
    # the same set: FastAPI generates the validation `422` on every operation
    # that takes a body or a typed parameter, and nothing in this codebase
    # raises it there — indexing only what routers raise left the single most
    # common failure in the API absent from the catalogue of failures.
    published = enrich(app)["paths"]
    index: dict[int, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for route in routes:
        where = f"`{route.method} {route.path}`"
        operation = published.get(route.path, {}).get(route.method.lower(), {})
        for code in operation.get("responses", {}):
            if code.isdigit() and int(code) >= 400:
                index[int(code)].setdefault("", []).append(where)
        for err in route.errors:
            if err.status_code < 400:
                continue
            index[err.status_code][err.detail or "(no detail)"].append(where)

    out: list[str] = [
        "# Error catalogue",
        "",
        _GENERATED,
        "",
        "## The body",
        "",
        "```json",
        '{ "detail": "Campaign is already running", "request_id": "…" }',
        "```",
        "",
        "`detail` is present on every error. `request_id` is present on `500` "
        "and mirrors the `X-Request-ID` response header; on other codes read "
        "the header. Validation failures (`422` raised by FastAPI rather than "
        "by a handler) put a list of `{loc, msg, type}` objects in `detail` "
        "instead of a string — that is the one shape variation, and it is "
        "FastAPI's.",
        "",
        "## Codes",
        "",
        "| Code | Meaning | Operations that can return it |",
        "| --- | --- | --- |",
    ]
    for code in sorted(index):
        title, guide = STATUS_GUIDE.get(code, ("Error", ""))
        count = len({op for ops in index[code].values() for op in ops})
        out.append(f"| [{code}](#{code}-{_anchor(title)}) | {title} | {count} |")
    out.append("")

    for code in sorted(index):
        title, guide = STATUS_GUIDE.get(code, ("Error", ""))
        out += [f"## {code} {title}", "", guide, ""]
        out += ["**Resolution.** " + RESOLUTION.get(code, "—"), ""]

        details = {d: ops for d, ops in index[code].items() if d}
        if details:

            out += ["| `detail` | Raised by |", "| --- | --- |"]
            for detail in sorted(details):
                ops = sorted(set(details[detail]))
                shown = ", ".join(ops[:6])
                if len(ops) > 6:
                    shown += f", and {len(ops) - 6} more"
                out.append(f"| `{detail}` | {shown} |")
            out.append("")
        else:
            implied = sorted({op for ops in index[code].values() for op in ops})
            out += [
                f"Not raised with a fixed message; it follows from how a route "
                f"is mounted. {len(implied)} operations can return it.",
                "",
            ]

    return "\n".join(out).rstrip() + "\n"


