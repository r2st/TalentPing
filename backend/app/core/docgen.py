def _auth_cell(route: RouteDoc) -> str:
    if route.admin_only:
        return "admin"
    if route.authenticated:
        return "bearer"
    return "public"


def _limit_cell(route: RouteDoc) -> str:
    if not route.rate_limit:
        return "—"
    limit = route.rate_limit
    return (
        f"{limit['max_requests']}/{limit['window_seconds']}s "
        f"per {limit['keyed_by']} (`{limit['scope']}`)"
    )


def render_reference(app: FastAPI) -> str:
    routes = route_docs(app)
    by_tag: dict[str, list[RouteDoc]] = defaultdict(list)
    for route in routes:
        by_tag[route.tag].append(route)

    order = [tag for tag, _ in TAG_DESCRIPTIONS if tag in by_tag]
    order += sorted(tag for tag in by_tag if tag not in dict(TAG_DESCRIPTIONS))
    descriptions = dict(TAG_DESCRIPTIONS)

    out: list[str] = [
        "# API reference",
        "",
        _GENERATED,
        "",
        f"{len(routes)} operations across {len(by_tag)} resource groups. The "
        "machine-readable form is [`openapi.json`](openapi.json); the failure "
        "codes are indexed by code in [`ERRORS.md`](ERRORS.md); the settings "
        "that change any of this behaviour are in "
        "[`ENVIRONMENT.md`](ENVIRONMENT.md).",
        "",
        "## Authentication",
        "",
        "Every route marked `bearer` or `admin` expects "
        "`Authorization: Bearer <token>`.",
        "",
        "1. `POST /api/v1/auth/register` creates the account and returns a "
        "token; `POST /api/v1/auth/login` takes "
        "`application/x-www-form-urlencoded` with `username` (the email "
        "address) and `password` and returns the same shape. Both are limited "
        "by client address, not by user — they are the two endpoints with no "
        "authenticated caller to key on.",
        "2. The token is a JWT signed with `JWT_SECRET`, valid for "
        "`ACCESS_TOKEN_EXPIRE_MINUTES` (a day by default).",
        "3. **There is no refresh endpoint.** A token is used until it expires "
        "and then replaced by logging in again. Adding one would mean issuing "
        "a longer-lived credential, and the revocation model below is built "
        "around short ones.",
        "4. Tokens carry a `token_version` claim checked against the account on "
        "every request. Changing a password increments it, which revokes every "
        "outstanding token for that account at once — including the one making "
        "the change. Those requests answer `401` with "
        "`Session has been revoked; sign in again`, which a client must treat "
        "as a logout rather than as a retryable failure.",
        "5. `admin` routes additionally require `is_admin`. The role is granted "
        "at login to addresses listed in `ADMIN_EMAILS`, so a newly listed "
        "address becomes an administrator on its next sign-in, not on restart.",
        "",
        "### Gmail OAuth",
        "",
        "Separate from the above, and per user rather than per deployment. "
        "`GET /api/v1/gmail/authorize` returns Google's consent URL carrying a "
        "signed `state`; the user consents; Google redirects to "
        "`GET /api/v1/gmail/callback`, which verifies `state`, exchanges the "
        "code and stores the refresh token encrypted with "
        "`TOKEN_ENCRYPTION_KEY`. The callback is the one authenticated-feeling "
        "route reached without a bearer token — the `state` parameter is what "
        "identifies the user. A revoked or expired grant is recorded on the "
        "account rather than raised, so subsequent polls report "
        "`gmail_unconfigured` instead of failing.",
        "",
        "### Public routes",
        "",
        "The `tracking` group is reached by a recipient's mail client or "
        "browser and cannot carry a token. Those routes are identified by an "
        "opaque per-message token in the path or query, never by user id.",
        "",
        "## Rate limits",
        "",
        "Two limiters. Per-user limits key on the authenticated account and "
        "guard work that costs money or holds a worker; per-address limits key "
        "on the client address and guard the credential surface. Scopes are "
        "separate budgets — spending one never refuses another.",
        "",
        "A refusal is `429` with `Retry-After` in whole seconds, plus "
        "`RateLimit-Limit`, `RateLimit-Remaining` and `RateLimit-Reset`. "
        "Successful responses on a limited route carry `RateLimit-Limit` too.",
        "",
        "> Behind a reverse proxy, per-address limits are only as correct as "
        "`TRUSTED_PROXY_HOPS`. Left at 0 with a proxy in front, every caller "
        "shares one bucket and ten failed logins refuse the login route for "
        "the whole deployment.",
        "",
    ]

    metered = sorted(
        (r for r in routes if r.rate_limit),
        key=lambda r: (r.rate_limit["scope"], r.path),  # type: ignore[index]
    )
    out += ["| Scope | Budget | Keyed by | Endpoints |", "| --- | --- | --- | --- |"]
    by_scope: dict[str, list[RouteDoc]] = defaultdict(list)
    for route in metered:
        by_scope[route.rate_limit["scope"]].append(route)  # type: ignore[index]
    for scope in sorted(by_scope):
        group = by_scope[scope]
        limit = group[0].rate_limit
        endpoints = "<br>".join(f"`{r.method} {r.path}`" for r in group)
        out.append(
            f"| `{scope}` | {limit['max_requests']} per "  # type: ignore[index]
            f"{limit['window_seconds']}s | {limit['keyed_by']} | "  # type: ignore[index]
            f"{endpoints} |"
        )
    out += ["", "## Webhooks and callbacks", "", WEBHOOKS_PROSE, ""]
    public = [r for r in routes if not r.authenticated]
    out += [
        "| Method | Path | Called by | How the caller is identified |",
        "| --- | --- | --- | --- |",
    ]
    for route in public:
        caller, identity = _caller_of(route)
        out.append(f"| `{route.method}` | `{route.path}` | {caller} | {identity} |")
    out += ["", "## Errors", "", ERRORS_SUMMARY, ""]

    out += ["## Resources", ""]
    for tag in order:
        out.append(f"- [{tag}](#{_anchor(tag)}) — {len(by_tag[tag])} operations")
    out.append("")

    for tag in order:
        out += [f"## {tag}", ""]
        if tag in descriptions:
            out += [descriptions[tag], ""]
        out += [
            "| Method | Path | Auth | Rate limit | Responses | Summary |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for route in by_tag[tag]:
            codes = " ".join(str(c) for c in route.status_codes)
            out.append(
                f"| `{route.method}` | `{route.path}` | {_auth_cell(route)} | "
                f"{_limit_cell(route)} | {codes} | {_one_line(route.summary, 90)} |"
            )
        out.append("")

    return "\n".join(out).rstrip() + "\n"


WEBHOOKS_PROSE = (
    "Everything the API answers without a bearer token, and why. None of these "
    "are reachable by a client of the product — they exist because something "
    "outside it calls in.\n\n"
    "**`POST /api/v1/gmail/webhook`** is the Cloud Pub/Sub push subscription "
    "for Gmail mailbox changes. Its only gate is the `?token=` query "
    "parameter, matched against `GMAIL_PUBSUB_TOKEN`, so that value is a "
    "credential and belongs in the URL registered with Pub/Sub and nowhere "
    "else. It answers `204` to everything — a valid notification, a bad token, "
    "an unparseable body — because Pub/Sub retries with backoff on any "
    "non-2xx, and retrying a message that will never parse is a loop rather "
    "than a recovery. Failures are logged, not returned.\n\n"
    "**`GET /api/v1/gmail/callback`** is the OAuth redirect target. Google "
    "sends the user here with `code` and `state`; `state` is signed and is "
    "what identifies the user, since the browser arriving is not carrying a "
    "bearer token. It must match the URI registered on the OAuth client "
    "exactly (`GOOGLE_OAUTH_REDIRECT_URI`), or Google refuses before any code "
    "is issued.\n\n"
    "**The tracking routes** are hit by a recipient's mail client or browser. "
    "`GET /api/v1/t/o/{token}.gif` returns the pixel; "
    "`GET /api/v1/t/c/{token}` records the click and answers `302` to the "
    "decoded target. Both are identified by an opaque per-message token, never "
    "by user id, and both answer normally when the token is unknown — a "
    "tracking endpoint that errored would show a broken image in somebody's "
    "inbox. Set `EMAIL_TRACKING_ENABLED=false` to stop stamping them into "
    "outbound mail.\n\n"
    "**The unsubscribe routes** back the `List-Unsubscribe` header. The `GET` "
    "is the human-facing link; the `POST` is RFC 8058 one-click, which mail "
    "providers call themselves with no user involved — which is why it cannot "
    "require a confirmation step. `/api/v1/unsubscribe` opts a recruiter out "
    "of outreach; `/api/v1/digest/unsubscribe` opts a user out of the weekly "
    "digest. They are different lists.\n"
)


def _caller_of(route: RouteDoc) -> tuple[str, str]:
    """Who reaches a public route, and what stands in for authentication.

    Keyed on the path rather than inferred, and driven off the generated list
    of unauthenticated routes — so a new public route appears in the table
    immediately, with an explicit "not described yet" rather than by being
    silently absent.
    """
    table = {
        "/api/v1/gmail/webhook": ("Google Cloud Pub/Sub", "`?token=` query parameter"),
        "/api/v1/gmail/callback": ("Google, redirecting the user", "signed `state`"),
        "/api/v1/t/o/{token}.gif": ("recipient's mail client", "opaque path token"),
        "/api/v1/t/c/{token}": ("recipient's browser", "opaque path token"),
        "/api/v1/unsubscribe": (
            "recipient, or their mail provider",
            "opaque token",
        ),
        "/api/v1/digest/unsubscribe": (
            "user, or their mail provider",
            "opaque token",
        ),
        "/api/v1/auth/login": ("any client", "credentials in the body"),
        "/api/v1/auth/register": ("any client", "n/a — this creates the account"),
        "/api/v1/health": ("monitoring", "n/a"),
        "/": ("anyone", "n/a"),
        # Not a callback, and the only unauthenticated route in an otherwise
        # fully-authenticated router. It is read by the SPA to tell "no jobs
        # found" from "this deployment cannot reach Google Jobs", and it
        # discloses which discovery sources are configured — booleans and a
        # fixed list of public board names, no keys — to anyone who asks.
        # Listed here because a public route that nobody meant to be public is
        # exactly what this table exists to surface.
        "/api/v1/jobs/providers/status": (
            "the SPA",
            "**nothing** — public, discloses which providers are configured",
        ),
    }
    return table.get(route.path, ("—", "**not described** — add it to `_caller_of`"))


ERRORS_SUMMARY = (
    "Every failure, including an unhandled one, answers with "
    "`{\"detail\": \"...\"}`; a 500 adds `\"request_id\"`, which is also the "
    "`X-Request-ID` response header. A client's error handler therefore reads "
    "one shape for every code. Full catalogue in [`ERRORS.md`](ERRORS.md)."
)


